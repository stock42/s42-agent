const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const templates = Object.entries(english).filter(([key]) => /\{\d+\}/.test(key))
  .sort(([a], [b]) => b.replace(/\{\d+\}/g, "").length - a.replace(/\{\d+\}/g, "").length)
  .map(([source, target]) => {
    const slots: string[] = [];
    const parts = source.split(/(\{\d+\})/g).map(part => {
      if (/^\{\d+\}$/.test(part)) { slots.push(part); return "([\\s\\S]*?)"; }
      return escape(part);
    });
    return { pattern: new RegExp("^" + parts.join("") + "$"), target, slots };
  });

export function translate(text: string, language: Language): string {
  if (language === "es") return Object.hasOwn(spanish, text) ? spanish[text]! : text;
  if (Object.hasOwn(english, text)) return english[text]!;
  for (const { pattern, target, slots } of templates) {
    const match = pattern.exec(text);
    if (match) return target.replace(/\{\d+\}/g, slot => match[slots.indexOf(slot) + 1] ?? slot);
  }
  // Prefixes used by harness notices: translate their own error text while
  // leaving the server/skill name and unknown external details unchanged.
  const notice = /^(MCP|Skill) ([^\n]+?): ([\s\S]*)$/.exec(text);
  if (notice) return `${notice[1]} ${notice[2]}: ${translate(notice[3]!, language)}`;
  return text;
}
